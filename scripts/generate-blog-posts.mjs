import { readFileSync, writeFileSync, existsSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, "..")
const postsDir = join(root, "wordpress_migration", "prepared", "posts")
const outFile = join(root, "app", "blog", "posts.generated.ts")

const index = JSON.parse(
  readFileSync(join(root, "wordpress_migration", "prepared", "index.json"), "utf-8")
)

const russianIds = new Set(index.languages.ru)

function loadPost(id) {
  const filePath = join(postsDir, `post-${id}.json`)
  if (!existsSync(filePath)) return null
  return JSON.parse(readFileSync(filePath, "utf-8"))
}

const importedPosts = []

for (const entry of index.posts) {
  if (entry.migrationStatus !== "ready") continue
  if (entry.language !== "et") continue
  if (russianIds.has(entry.id)) continue

  const post = loadPost(entry.id)
  if (!post) {
    console.warn(`Post JSON not found for ID ${entry.id}, skipping`)
    continue
  }

  importedPosts.push({
    id: post.id,
    title: post.title,
    slug: post.slug,
    date: post.date,
    excerpt: post.excerpt,
    contentHtml: post.contentHtml,
    featuredImage: post.featuredImage,
    featuredImageSource: post.featuredImageSource,
    language: post.language,
    sourceBackup: post.sourceBackup,
  })
}

importedPosts.sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())

const ts = `// Auto-generated by scripts/generate-blog-posts.mjs — do not edit by hand
export interface BlogPost {
  id: number
  title: string
  slug: string
  date: string
  excerpt: string
  contentHtml: string
  featuredImage: string
  featuredImageSource: "wordpress" | "first-content-image"
  language: string
  sourceBackup: string
}

export const blogPosts: BlogPost[] = ${JSON.stringify(importedPosts, null, 2)}
`

writeFileSync(outFile, ts, "utf-8")
console.log(`Generated ${importedPosts.length} blog posts → ${outFile}`)
